"""Accounts through the real page: register, stay logged in, log out and in, two devices, offline, session loss."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from harness import *
from playwright.sync_api import sync_playwright

c = Checks(); errs = []
G = 'window.__GC'
game = lambda pg: pg.evaluate('(() => { const s = window.__GC.store.s; return { coins: s.coins, inv: s.inv, opened: s.opened }; })()')
server = lambda u: rpc('me', {'rev': -1}, u['token'])[1]
down = lambda route: route.abort()

def wait_auth(pg):
    pg.wait_for_function('window.__GC && window.__GC.auth === true', timeout=120000)

with sync_playwright() as p:
    b = launch(p)
    # --- a first visit: login screen, nothing of the game reachable
    pg = page_for(b, None, errors=errs)
    pg.goto(URL); wait_auth(pg)
    c.ok(pg.is_visible('#auth .auth-box'), 'a first visit shows the login screen')
    c.ok(not pg.evaluate("document.querySelector('#app').classList.contains('on')"), 'the game stays hidden until login')
    c.eq(pg.inner_text('#authGo'), 'LOG IN', 'it starts on Log in')
    pg.click('#authGo'); c.ok('Enter your username' in pg.inner_text('#authErr'), 'empty form: asks for the username')
    name = new_name('Erika')
    pg.fill('#authName', name); pg.fill('#authPass', 'whatever1'); pg.click('#authGo')
    pg.wait_for_function("document.querySelector('#authErr').textContent.includes('Wrong username')", timeout=8000)
    c.ok(True, 'unknown account: "Wrong username or password."')
    # --- create the account
    pg.click('.auth-tabs button[data-m=register]')
    c.eq(pg.inner_text('#authGo'), 'CREATE ACCOUNT', 'the button names what it does')
    c.ok(pg.is_visible('#authPassHint'), 'registration explains the password rule')
    pg.fill('#authName', 'x'); pg.click('#authGo')
    c.ok('does not work' in pg.inner_text('#authErr'), 'a name that is too short is refused on the page')
    pg.fill('#authName', name); pg.fill('#authPass', '123'); pg.click('#authGo')
    c.ok('at least 6' in pg.inner_text('#authErr'), 'a short password is refused on the page')
    pg.fill('#authPass', 'geheim12'); pg.click('#authGo')
    pg.wait_for_function(G + '.ready === true', timeout=60000)
    pg.evaluate(G + '.chest.stop()')
    c.eq(pg.evaluate(G + '.mode'), 'account', 'after registering the game opens')
    c.eq(pg.evaluate(G + '.net.user.name'), name, 'as the new player')
    c.ok(pg.evaluate("document.querySelector('#auth').hidden"), 'the login screen is gone')
    sess = pg.evaluate("JSON.parse(localStorage.getItem('gundichest.session.v1'))")
    U = {'name': name, 'pass': 'geheim12', 'token': sess['token'], 'id': sess['user']['id']}
    c.ok('geheim12' not in pg.evaluate('JSON.stringify(localStorage)'), 'the password is not kept in the browser')
    # --- sound: off by default, switch in the top bar, same switch in settings
    c.eq(pg.get_attribute('#btnSound', 'aria-pressed'), 'false', 'sound is off by default')
    order = pg.evaluate("[...document.querySelectorAll('.top-right > *')].map(e => e.id)")
    c.eq(order, ['coinPill', 'btnSound', 'btnSettings'], 'top bar: coins, sound, settings')
    pg.click('#btnSound')
    c.eq([pg.get_attribute('#btnSound', 'aria-pressed'), pg.evaluate(G + '.store.s.settings.snd')], ['true', True], 'a tap switches sound on')
    pg.click('#btnSettings'); pg.wait_for_selector('.sheet.on')
    c.ok(name in pg.inner_text('.sheet.on'), 'settings name the account')
    snd = pg.locator('.sheet.on .set-row', has_text='Sound').locator('.toggle')
    c.eq(snd.get_attribute('aria-checked'), 'true', 'settings show the same sound switch')
    snd.click()
    c.eq(pg.get_attribute('#btnSound', 'aria-pressed'), 'false', 'switching it off there updates the top bar')
    pg.click('.sheet.on .x-btn'); pg.wait_for_timeout(450)
    # --- playing is saved to the account
    pg.evaluate("(() => { const S = window.__GC.store; S.give('i7', 2); S.give('i17', 1); S.addCoins(900); S.s.opened = 3; S.save(); })()")
    c.ok(pg.evaluate(G + '.net.syncNow()'), 'a save goes through')
    sv = server(U)
    c.eq([sv['state']['coins'], sv['state']['inv'], sv['state']['opened'], sv['rev']], [900, {'i7': 2, 'i17': 1}, 3, 1], 'the server has the game')
    # --- reload: still logged in, same game
    pg.reload(); pg.wait_for_function(G + ' && ' + G + '.ready === true', timeout=120000); pg.evaluate(G + '.chest.stop()')
    c.eq(pg.evaluate(G + '.auth'), None, 'a reload does not ask to log in again')
    c.eq(game(pg), {'coins': 900, 'inv': {'i7': 2, 'i17': 1}, 'opened': 3}, 'and shows the same game')
    # --- a second device logs in and gets the game
    d2 = page_for(b, None, errors=errs)
    d2.goto(URL); wait_auth(d2)
    d2.fill('#authName', name.upper()); d2.fill('#authPass', 'wrong-pass'); d2.click('#authGo')
    d2.wait_for_function("document.querySelector('#authErr').textContent.includes('Wrong username')", timeout=8000)
    c.ok(d2.evaluate(G + '.auth'), 'a wrong password does not get in')
    d2.fill('#authPass', 'geheim12'); d2.click('#authGo')
    d2.wait_for_function(G + '.ready === true', timeout=60000); d2.evaluate(G + '.chest.stop()')
    c.eq(game(d2), {'coins': 900, 'inv': {'i7': 2, 'i17': 1}, 'opened': 3}, 'second device: the name works in any case and the game is there')
    # --- both devices play; the one that saves second gets the stored game instead of overwriting it
    pg.evaluate("(() => { const S = window.__GC.store; S.addCoins(100); })()"); pg.evaluate(G + '.net.syncNow()')
    d2.evaluate("(() => { const S = window.__GC.store; S.give('i0', 1); })()")
    d2.evaluate(G + '.net.syncNow().catch(() => 0)')
    wait_until(lambda: game(d2)['coins'] == 1000, 8)
    c.eq(game(d2), {'coins': 1000, 'inv': {'i7': 2, 'i17': 1}, 'opened': 3}, 'second device takes over the newer save')
    c.ok('another device' in d2.inner_text('#toasts'), 'and says why')
    c.eq(server(U)['state']['coins'], 1000, 'the server keeps the first save')
    # --- log out
    pg.click('#btnSettings'); pg.wait_for_selector('.sheet.on #setLogout'); pg.click('#setLogout')
    wait_auth(pg)
    c.eq(pg.evaluate("localStorage.getItem('gundichest.session.v1')"), None, 'logging out forgets the session')
    c.eq(rpc('me', {}, U['token'])[0], 401, 'and the server ends it')
    # --- the second device is still logged in; when its session ends it lands on the login screen
    rpc('logout', {}, d2.evaluate("JSON.parse(localStorage.getItem('gundichest.session.v1')).token"))
    d2.evaluate(G + '.net.pollNow()')
    wait_auth(d2)
    c.ok('log in again' in d2.inner_text('#authErr').lower(), 'a session that ended elsewhere leads back to the login with a reason')
    d2.close()
    # --- server not reachable on a first visit: playing offline is offered, and that progress moves into the account
    g = page_for(b, None, errors=None)
    g.route('**/api/rpc', down)
    g.goto(URL); wait_auth(g)
    c.ok(not g.is_visible('#authAlt'), 'the offline option is not there while nothing has failed')
    g.fill('#authName', name); g.fill('#authPass', 'geheim12'); g.click('#authGo')
    g.wait_for_selector('#authAlt:not([hidden])', timeout=20000)
    c.ok('Cannot reach the server' in g.inner_text('#authErr'), 'a login without connection says so')
    g.click('#authOffline')
    g.wait_for_function(G + '.ready === true', timeout=60000); g.evaluate(G + '.chest.stop()')
    c.eq(g.evaluate(G + '.mode'), 'local', 'offline play starts')
    g.evaluate("(() => { const S = window.__GC.store; S.give('i14', 2); S.addCoins(55); S.s.opened = 2; S.save(); S.saveNow(); })()")
    g.click('#nav button[data-go=trade]'); g.wait_for_selector('#trLogin')
    c.ok('needs an account' in g.inner_text('#view-trade'), 'trading explains that it needs an account')
    g.unroute('**/api/rpc')
    g.click('#trLogin'); wait_auth(g)
    c.ok(not g.is_visible('#authAlt'), 'with the server back the login screen is the normal one')
    n2 = new_name('Gast')
    g.click('.auth-tabs button[data-m=register]'); g.fill('#authName', n2); g.fill('#authPass', 'geheim12'); g.click('#authGo')
    g.wait_for_function(G + '.ready === true', timeout=60000); g.evaluate(G + '.chest.stop()')
    c.eq(game(g), {'coins': 55, 'inv': {'i14': 2}, 'opened': 2}, 'the new account starts with the offline progress')
    tok = g.evaluate("JSON.parse(localStorage.getItem('gundichest.session.v1')).token")
    c.eq(rpc('me', {'rev': -1}, tok)[1]['state']['inv'], {'i14': 2}, 'and the server has it')
    c.eq(g.evaluate("JSON.parse(localStorage.getItem('gundichest.save.v1')).coins"), 0, 'the device save is emptied so it is not used twice')
    # --- the server drops out while playing: the game goes on, the save follows later
    g.route('**/api/rpc', down)
    g.evaluate("(() => { const S = window.__GC.store; S.addCoins(45); })()")
    g.evaluate(G + '.net.syncNow().catch(() => 0)'); g.wait_for_timeout(400)
    c.eq([g.evaluate(G + '.net.online'), g.evaluate(G + '.store.sync.dirty')], [False, True], 'offline is noticed, the change waits')
    g.reload(); g.wait_for_function(G + ' && ' + G + '.ready === true', timeout=120000); g.evaluate(G + '.chest.stop()')
    c.eq([g.evaluate(G + '.mode'), game(g)['coins']], ['account', 100], 'a reload without server still opens the game from this device')
    g.wait_for_timeout(500)
    c.ok('Offline' in g.inner_text('#toasts'), 'with a note that it is offline')
    g.unroute('**/api/rpc')
    g.evaluate(G + '.net.syncNow().catch(() => 0)')
    wait_until(lambda: rpc('me', {'rev': -1}, tok)[1]['state']['coins'] == 100, 10)
    c.eq(rpc('me', {'rev': -1}, tok)[1]['state']['coins'], 100, 'once the server is back the change is saved')
    # --- change password, delete account
    g.click('#btnSettings'); g.wait_for_selector('.sheet.on'); g.click('.sheet.on button:has-text("Change password")')
    g.wait_for_selector('#pwOld'); g.fill('#pwOld', 'nope'); g.fill('#pwNew', 'neues-pw-1'); g.click('.pw-form button[type=submit]')
    g.wait_for_function("document.querySelector('.pw-form .auth-err').textContent.includes('not your current password')", timeout=8000)
    g.fill('#pwOld', 'geheim12'); g.click('.pw-form button[type=submit]')
    g.wait_for_function("!document.querySelector('#pwOld')", timeout=8000)
    c.eq([rpc('login', {'name': n2, 'pass': 'geheim12'})[0], rpc('login', {'name': n2, 'pass': 'neues-pw-1'})[0]], [401, 200], 'the password was changed')
    g.wait_for_timeout(500)
    g.click('.sheet.on button:has-text("Delete account")')
    g.wait_for_selector('#pwDel'); g.fill('#pwDel', 'neues-pw-1'); g.click('.pw-form button[type=submit]')
    wait_auth(g)
    c.eq(rpc('login', {'name': n2, 'pass': 'neues-pw-1'})[0], 401, 'a deleted account is gone')
    b.close()
c.done(errs)
